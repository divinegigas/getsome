"""Synthetic demo library: a few fake shows with burned-in titles and timecodes.

Lets you try TV mode without pointing at a real library, and the visible
timecode makes it easy to check that tuning in lands at the right spot.
Episodes get TinyMediaManager-style .nfo files.
"""

from __future__ import annotations

import random
import shutil
import subprocess
from pathlib import Path

from . import model, paths
from .assets_gen import _esc, video_codec_args

SHOWS = {
    "Neon Patrol": ("0xFF2BD6", 4, (150, 200)),
    "Cosmic Diner": ("0x00F0FF", 4, (120, 170)),
    "Saturday Toons": ("0xFFE600", 6, (60, 100)),
    "Late Movie": ("0x7CFF4F", 2, (300, 360)),
}

FONT = paths.FONTS_DIR / "TiltNeon.ttf"
# invented cast (name, role) per show, for the trivia cards
CAST = {
    "Neon Patrol": [("Dana Vexley", "Captain Rayne"), ("Marco Lume", "Officer Glint")],
    "Cosmic Diner": [("Ruth Okafor", "Big Lou"), ("Tad Kimura", "Zeph the Cook")],
    "Saturday Toons": [("Penny Ash", "Professor Wobble")],
}


def _cast_xml(show: str, roles: bool) -> str:
    return "".join(f"  <actor>\n    <name>{n}</name>\n" + (f"    <role>{r}</role>\n" if roles else "") + "  </actor>\n"
                   for n, r in CAST.get(show, []))


def demo_media_dir() -> Path:
    return paths.data_dir() / "demo-media"


def _episode(out: Path, show: str, season: int, ep: int, seconds: int, color: str) -> None:
    font = _esc(FONT)
    label = f"{show}  S{season:02d}E{ep:02d}".replace(":", "\\:")
    vf = ",".join([
        f"drawtext=fontfile='{font}':text='{label}':fontsize=44:fontcolor={color}:x=(w-text_w)/2:y=h*0.30:box=1:boxcolor=black@0.6:boxborderw=12",
        f"drawtext=fontfile='{font}':text='%{{pts\\:hms}}':fontsize=64:fontcolor=white:x=(w-text_w)/2:y=h*0.55:box=1:boxcolor=black@0.6:boxborderw=12",
    ])
    hz = 300 + 60 * ep
    subprocess.run([
        shutil.which("ffmpeg") or "ffmpeg", "-y", "-loglevel", "error",
        "-f", "lavfi", "-i", f"testsrc2=size=640x360:rate=25:duration={seconds}",
        "-f", "lavfi", "-i", f"sine=frequency={hz}:sample_rate=48000:duration={seconds}",
        "-vf", vf, "-af", "volume=0.08",
        *video_codec_args("fast"), "-g", "50",
        "-c:a", "aac", "-b:a", "64k", "-shortest", str(out),
    ], check=True)
    out.with_suffix(".nfo").write_text(
        "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\" ?>\n"
        f"<episodedetails>\n  <title>Episode {ep}: The {random.choice(['Glowing', 'Static', 'Midnight', 'Chrome', 'Laser'])} "
        f"{random.choice(['Signal', 'Caper', 'Rerun', 'Broadcast', 'Remote'])}</title>\n"
        f"  <showtitle>{show}</showtitle>\n  <season>{season}</season>\n  <episode>{ep}</episode>\n"
        "  <plot>A demo episode generated by Neon Cable 42.</plot>\n" + _cast_xml(show, False) + "</episodedetails>\n"
    )


def _ff(*args: str) -> None:
    subprocess.run([shutil.which("ffmpeg") or "ffmpeg", "-y", "-loglevel", "error", *args], check=True)


def _artwork(show_dir: Path, show: str, color: str) -> None:
    """TinyMediaManager-style artwork (poster, fanart, clearlogo, episode thumbs) so the
    artwork cards and transitions can be tried with the demo."""
    font = _esc(FONT)
    name = show.upper().replace(":", "\\:")
    c2 = "0x" + "".join(f"{255 - int(color[i:i + 2], 16):02X}" for i in (2, 4, 6))
    if not (show_dir / "poster.jpg").exists():
        _ff("-f", "lavfi", "-i", f"gradients=s=600x900:c0={color}:c1=0x10002A:x0=0:y0=0:x1=600:y1=900:d=1",
            "-frames:v", "1", "-vf",
            f"drawtext=fontfile='{font}':text='{name}':fontsize=60:fontcolor=white:x=(w-text_w)/2:y=h*0.75:"
            f"borderw=4:bordercolor=black", str(show_dir / "poster.jpg"))
    if not (show_dir / "fanart.jpg").exists():
        _ff("-f", "lavfi", "-i", f"gradients=s=1280x720:c0=0x10002A:c1={color}:c2={c2}:n=3:x0=0:y0=0:x1=1280:y1=720:d=1",
            "-frames:v", "1", "-vf", "drawgrid=w=80:h=80:t=2:c=white@0.15", str(show_dir / "fanart.jpg"))
    if not (show_dir / "clearlogo.png").exists():
        _ff("-f", "lavfi", "-i", "color=c=black@0.0:s=800x310,format=rgba", "-frames:v", "1", "-vf",
            f"format=rgba,drawtext=fontfile='{font}':text='{name}':fontsize=96:fontcolor={color}:"
            f"x=(w-text_w)/2:y=(h-text_h)/2:borderw=6:bordercolor=white", str(show_dir / "clearlogo.png"))
    for ep in sorted(show_dir.glob("Season */*.mp4")):
        thumb = ep.with_name(ep.stem + "-thumb.jpg")
        if not thumb.exists():
            _ff("-ss", "5", "-i", str(ep), "-frames:v", "1", str(thumb))


def make_demo(on_line=print) -> None:
    random.seed(42)
    root = demo_media_dir()
    for show, (color, count, (lo, hi)) in SHOWS.items():
        folder = root / show / "Season 01"
        folder.mkdir(parents=True, exist_ok=True)
        (root / show / "tvshow.nfo").write_text(
            f"<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<tvshow>\n  <title>{show}</title>\n{_cast_xml(show, True)}</tvshow>\n")
        for ep in range(1, count + 1):
            out = folder / f"{show} - S01E{ep:02d}.mp4"
            if not out.exists():
                on_line(f"rendering {out.name}")
                _episode(out, show, 1, ep, random.randint(lo, hi), color)
        if show != "Late Movie":           # one show without artwork, like a bare folder
            on_line(f"artwork for {show}")
            _artwork(root / show, show, color)

    on_line("writing demo channels")
    chans = [c for c in model.load() if c.number not in (3, 5, 9)]
    chans += [
        model.Channel(3, "Neon TV", "marathon", model.SEQUENTIAL, 1,
                      [model.ShowRef(str(root / "Neon Patrol")), model.ShowRef(str(root / "Cosmic Diner"))]),
        model.Channel(5, "Toon Zone", "shuffle", model.SHUFFLE, 1, [model.ShowRef(str(root / "Saturday Toons"))]),
        model.Channel(9, "Shuffle Mix", "shuffle", model.SHUFFLE, 1, [model.ShowRef(str(root / s)) for s in SHOWS]),
    ]
    model.save(chans)
